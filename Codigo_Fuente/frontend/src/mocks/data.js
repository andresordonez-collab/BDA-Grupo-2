const FACTOR_HORA = [
  0, 0, 0, 0, 0, 0, 1, 3, 7, 4, 2, 3, 5, 3, 2, 3, 5, 7, 8, 5, 3, 2, 1, 0,
];

export const demanda = estaciones.flatMap((estacion, indiceEstacion) => {
  const factorEstacion = 0.6 + indiceEstacion * 0.12;

  return Array.from({ length: 24 }, (_, hora) => {
    const base = FACTOR_HORA[hora] * factorEstacion;

    return {
      idEstacion: estacion.idEstacion,
      nombreEstacion: estacion.nombreEstacion,
      franjaHoraria: hora,
      viajesIniciados: Math.max(0, Math.round(base)),
      viajesFinalizados: Math.max(0, Math.round(base * 0.8)),
    };
  });
});
